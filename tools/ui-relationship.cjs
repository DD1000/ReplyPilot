  await page.locator('[name=person-mode][value=manual]').check();
  await page.getByRole('button',{name:'Save profile',exact:true}).click();
  await page.waitForFunction(async()=>(await demoApi('conversation',{thread:2})).relationship.relationshipKind==='Family');
  assert.equal(await page.locator('#relationship-context').inputValue(),'','Dynamics can be blank');
  await closeSetup();await page.getByRole('button', { name: 'Back to conversations' }).click();
  await page.locator('.row').filter({ hasText:'Maya Chen' }).click();
  await openSetup();
  assert.equal(await field.inputValue(), note);
  await page.reload();
  await openSetup();
  assert.equal(await field.inputValue(), note, 'Saved note must persist across reload');
  assert(await page.locator('[name=relationship-kind][value=Friend]').isChecked());
  assert(await page.locator('[name=person-tone][value=Professional]').isChecked());
