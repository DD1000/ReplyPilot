  await field.fill(note);
  await page.locator('[name=person-mode][value=manual]').check();
  await page.locator('[name=person-mode][value=off]').check();
  assert.equal(await field.inputValue(), note, 'Changing reply mode must preserve unsaved context');
  assert(await page.locator('[name=person-tone][value=Professional]').isChecked());
  await closeSetup();
  await page.getByRole('button', { name: 'Redraft', exact: true }).click();
  assert((await page.locator('#toast').textContent()).includes('Save or clear'));
  assert.equal(await page.locator('#draft').inputValue(), originalDraft);
  await openSetup();
  await page.getByRole('button', { name: 'Save profile', exact: true }).click();
